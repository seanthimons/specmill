# Reuses the prune fixtures; run from the repository root.
fixtures <- new.env()
sys.source('tests/prune.R', envir = fixtures)

tree_state <- function(root) {
  files <- list.files(root, recursive = TRUE, all.files = TRUE, full.names = TRUE)
  stats::setNames(unname(tools::md5sum(files)), files)
}

regeneration_report_acceptance <- function() {
  root <- fixtures$prune_fixture()
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  fixtures$prune_services(root, c('keep', 'old'))
  stopifnot(!inherits(fixtures$prune_run(root, 'apply'), 'error'))
  # The owner of /other is replaced, so its output is no longer generated.
  fixtures$prune_services(root, 'keep')
  writeLines('x <- 1', file.path(root, 'R/hand.R'))
  writeLines(
    c('# Generated with specmill; do not edit by hand.', 'y <- 1'),
    file.path(root, 'R/stray.R')
  )
  dir.create(file.path(root, 'man'))
  writeLines('% Generated by roxygen2: do not edit by hand', file.path(root, 'man/stray.Rd'))
  unlink(file.path(root, 'R/demo_good.R'))
  before <- tree_state(root)
  temp_before <- list.files(tempdir())
  report <- suppressMessages(specmill::regeneration_report(root))
  files <- stats::setNames(report$files$category, report$files$file)
  stopifnot(
    identical(unname(files[['R/demo_good.R']]), 'added'),
    identical(unname(files[['R/demo_other.R']]), 'would_remove'),
    report$files$prune_eligible[report$files$file == 'R/demo_other.R'],
    identical(unname(files[['R/hand.R']]), 'hand_written'),
    identical(unname(files[['R/stray.R']]), 'unowned_generated'),
    identical(unname(files[['man/stray.Rd']]), 'unowned_generated'),
    identical(
      report$files$owner[report$files$file == 'R/demo_other.R'],
      'old'
    ),
    identical(tree_state(root), before),
    identical(list.files(tempdir()), temp_before)
  )
  # An edited orphan is flagged as something prune would refuse.
  other <- file.path(root, 'R/demo_other.R')
  cat('# edited\n', file = other, append = TRUE)
  before <- tree_state(root)
  report <- suppressMessages(specmill::regeneration_report(root))
  row <- report$files[report$files$file == 'R/demo_other.R', ]
  stopifnot(
    identical(row$category, 'would_remove'),
    isFALSE(row$prune_eligible),
    identical(tree_state(root), before)
  )
  # A hand-edited owned file at a desired path is a conflict; a gone file with
  # a record is still reported.
  stopifnot(!inherits(fixtures$prune_run(root, 'apply'), 'error'))
  cat('# edited\n', file = file.path(root, 'R/demo_good.R'), append = TRUE)
  unlink(other)
  before <- tree_state(root)
  report <- suppressMessages(specmill::regeneration_report(root))
  files <- stats::setNames(report$files$category, report$files$file)
  stopifnot(
    identical(unname(files[['R/demo_good.R']]), 'edited_conflict'),
    identical(unname(files[['R/demo_other.R']]), 'would_remove'),
    identical(tree_state(root), before)
  )
  stopifnot(any(grepl('would_remove', capture.output(print(report)))))
  cat('regeneration report ok\n')
}

if (sys.nframe() == 0L) {
  regeneration_report_acceptance()
}
