# Regressions for issues 216 (policy partial match), 217 (title period)
# and 218 (manual tests passed to apply_files).

policy_version_without_policy_acceptance <- function() {
  schema <- system.file(
    'catalogue/schema.json',
    package = 'specmill',
    mustWork = TRUE
  )
  stage <- tempfile('policy-version-')
  dir.create(stage)
  on.exit(unlink(stage, recursive = TRUE), add = TRUE)
  plan <- specmill::generate_client(
    stage,
    list(files = schema, helper = 'h', policy_version = 'x'),
    'plan'
  )
  stopifnot(length(plan$operations) > 0L)
}

title_period_acceptance <- function() {
  docs <- specmill:::operation_documentation(
    list(summary = 'Get a thing.', parameters = list())
  )
  stopifnot(startsWith(docs, "#' Get a thing\n"))
}

scaffold_skips_manual_acceptance <- function() {
  root <- tempfile('scaffold-')
  dir.create(file.path(root, 'tests/testthat'), recursive = TRUE)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  context <- new.env(parent = asNamespace('specmill'))
  specmill::bind_tools('test_scaffold', context)
  specmill::bind_tools('test_helpers', context)
  header <- '# Generated by test scaffold'
  context$tg_config <- list(
    test_dir = 'tests/testthat',
    generated_header = header,
    legacy_metadata_header = '# legacy generated'
  )
  manual <- 'tests/testthat/test-manual.R'
  writeLines('# hand written', file.path(root, manual))
  desired <- list(
    list(
      function_name = 'manual',
      file = manual,
      text = paste0(header, '\n1\n')
    ),
    list(
      function_name = 'fresh',
      file = 'tests/testthat/test-fresh.R',
      text = paste0(header, '\n2\n')
    )
  )
  dry <- context$tg_scaffold_generated_tests(desired, root, dry_run = TRUE)
  stopifnot(
    identical(dry$writes$manual$action, 'skipped_manual'),
    !manual %in% vapply(dry$plan, `[[`, character(1), 'file')
  )
  context$tg_scaffold_generated_tests(desired, root)
  stopifnot(
    file.exists(file.path(root, 'tests/testthat/test-fresh.R')),
    identical(readLines(file.path(root, manual)), '# hand written')
  )
}

if (sys.nframe() == 0L) {
  policy_version_without_policy_acceptance()
  title_period_acceptance()
  scaffold_skips_manual_acceptance()
}
